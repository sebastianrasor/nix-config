use axum::{
    http::{StatusCode, Uri, header},
    response::{IntoResponse, Response},
};
use axum_extra::{
    extract::TypedHeader,
    headers::{ETag, IfNoneMatch},
};
use http_encoding_headers::{AcceptEncoding, Encoding};

include!(concat!(env!("OUT_DIR"), "/asset_table.rs"));

pub const CACHE_CONTROL_IMMUTABLE: &str = "public, max-age=31536000, immutable";
const CACHE_CONTROL_NO_STORE: &str = "no-store, no-cache, must-revalidate";
const CACHE_CONTROL_REVALIDATE: &str = "max-age=300, must-revalidate";

/// One pre-encoded representation of an asset.
#[derive(Debug)]
struct EncodedAsset {
    encoding: Encoding,
    /// Quoted SHA-256 digest of `data`.
    etag: &'static str,
    data: &'static [u8],
}

/// A file embedded at build time in every content-coding generated by `build.rs`.
#[derive(Debug)]
struct ConstAsset {
    content_type: &'static str,
    variants: &'static [EncodedAsset],
}

impl ConstAsset {
    fn preferred_variant(&self, accept_encoding: Option<&AcceptEncoding>) -> &EncodedAsset {
        let offered = self.variants.iter().map(|variant| &variant.encoding);
        let wanted = accept_encoding
            .and_then(|accept_encoding| accept_encoding.preferred_allowed(offered))
            .unwrap_or(&Encoding::Identity);

        self.variants
            .iter()
            .find(|variant| &variant.encoding == wanted)
            .expect("build.rs emits an identity variant for every asset")
    }
}

pub async fn handler(
    accept_encoding: Option<TypedHeader<AcceptEncoding>>,
    if_none_match: Option<TypedHeader<IfNoneMatch>>,
    uri: Uri,
) -> Response {
    let path = uri.path();

    let Some(asset) = ASSET_MAP.get(path) else {
        return (
            StatusCode::NOT_FOUND,
            [(header::CACHE_CONTROL, CACHE_CONTROL_NO_STORE)],
        )
            .into_response();
    };

    let variant = asset.preferred_variant(accept_encoding.as_deref());

    let cache_control = if path.starts_with(DIGEST_PREFIX) {
        CACHE_CONTROL_IMMUTABLE
    } else {
        CACHE_CONTROL_REVALIDATE
    };
    let headers = [
        (header::VARY, "Accept-Encoding"),
        (header::ETAG, variant.etag),
        (header::CACHE_CONTROL, cache_control),
    ];

    if let Some(TypedHeader(if_none_match)) = if_none_match {
        let etag: ETag = variant
            .etag
            .parse()
            .expect("build.rs emits valid quoted ETags");
        if !if_none_match.precondition_passes(&etag) {
            return (StatusCode::NOT_MODIFIED, headers).into_response();
        }
    }

    let content_encoding = (variant.encoding != Encoding::Identity)
        .then(|| [(header::CONTENT_ENCODING, variant.encoding.to_string())]);

    (
        headers,
        [(header::CONTENT_TYPE, asset.content_type)],
        content_encoding,
        variant.data,
    )
        .into_response()
}
